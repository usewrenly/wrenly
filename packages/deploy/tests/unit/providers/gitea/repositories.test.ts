import { expect, test } from 'bun:test'
import { createPrivateRepository, readPrivateRepository } from '../../../../src/providers/gitea/repositories'
import { DeploymentProviderError, type DeploymentProviderClient } from '../../../../src/http/provider-client'
const signal = new AbortController().signal
const valid = { id: 42, name: 'wrenly-project', owner: { login: 'apps' }, private: true, private_extra: 'secret' }
function client(value: unknown): DeploymentProviderClient { return { request: async () => value } }

test('repository creation is private and returns only verified identity', async () => {
  const provider: DeploymentProviderClient = { request: async (method, endpoint, body) => {
    expect(method).toBe('POST'); expect(endpoint).toBe('/api/v1/orgs/apps/repos')
    expect(body).toEqual({ name: 'wrenly-project', private: true, auto_init: false, description: 'Generated by Wrenly' })
    return valid
  } }
  expect(await createPrivateRepository(provider, 'apps', 'wrenly-project', signal)).toEqual({ id: '42', owner: 'apps', name: 'wrenly-project' })
})

test('public, wrong-owner, wrong-name and changed remote IDs are rejected', async () => {
  for (const value of [{ ...valid, private: false }, { ...valid, owner: { login: 'foreign' } }, { ...valid, name: 'other' }, { ...valid, id: 43 }])
    await expect(readPrivateRepository(client(value), 'apps', 'wrenly-project', '42', signal)).rejects.toThrow('validation failed')
  expect(await readPrivateRepository(client(valid), 'apps', 'wrenly-project', '42', signal)).toEqual({ id: '42', owner: 'apps', name: 'wrenly-project' })
})

test('only an unknown repository HTTP 404 means absent; known disappearance and auth failures stop', async () => {
  for (const status of [404, 401, 500]) {
    const provider: DeploymentProviderClient = { request: async () => { throw new DeploymentProviderError('http_error', status) } }
    if (status === 404) {
      expect(await readPrivateRepository(provider, 'apps', 'wrenly-project', undefined, signal)).toBeNull()
      await expect(readPrivateRepository(provider, 'apps', 'wrenly-project', '42', signal)).rejects.toThrow()
    } else await expect(readPrivateRepository(provider, 'apps', 'wrenly-project', undefined, signal)).rejects.toThrow()
  }
})

