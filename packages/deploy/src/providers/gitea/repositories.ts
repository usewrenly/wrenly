/**
 * Private Gitea repository administration
 * Used by publishing execution and reconciliation to establish remote repository identity.
 * Creates private repositories and verifies owner, name and saved remote ID.
 * Does not push source; source-snapshots owns Git transport. Ambiguous mutations require executor reconciliation.
 */
import type { DeploymentProviderClient } from "../../http/provider-client";
import { DeploymentProviderError } from "../../http/provider-client";

export interface PrivateRepository {
  id: string;
  owner: string;
  name: string;
}
export class PrivateRepositoryError extends Error {
  constructor(
    public readonly code:
      | "invalid_input"
      | "invalid_identity"
      | "repository_public"
      | "invalid_deploy_key",
  ) {
    super(`Private repository validation failed (${code}).`);
    this.name = "PrivateRepositoryError";
  }
}
function record(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}
function identifier(value: unknown): value is string {
  return typeof value === "string" && /^[a-zA-Z0-9_-]{1,100}$/.test(value);
}
function remoteId(value: unknown): string {
  if (typeof value !== "number" || !Number.isSafeInteger(value) || value < 1)
    throw new PrivateRepositoryError("invalid_identity");
  return String(value);
}
/** Discard extra provider fields and reject a repository replaced under the same name. */
function repository(
  value: unknown,
  owner: string,
  name: string,
  expectedId?: string,
): PrivateRepository {
  if (
    !record(value) ||
    value.name !== name ||
    !record(value.owner) ||
    value.owner.login !== owner
  )
    throw new PrivateRepositoryError("invalid_identity");
  if (value.private !== true)
    throw new PrivateRepositoryError("repository_public");
  const id = remoteId(value.id);
  if (expectedId !== undefined && id !== expectedId)
    throw new PrivateRepositoryError("invalid_identity");
  return { id, owner, name };
}
function validateNames(owner: string, name: string): void {
  if (!identifier(owner) || !identifier(name))
    throw new PrivateRepositoryError("invalid_input");
}

/** Reads one exact repository; only an HTTP 404 means absent. Public repos always fail. */
export async function readPrivateRepository(
  client: DeploymentProviderClient,
  owner: string,
  name: string,
  expectedId: string | undefined,
  signal: AbortSignal,
): Promise<PrivateRepository | null> {
  validateNames(owner, name);
  try {
    return repository(
      await client.request(
        "GET",
        `/api/v1/repos/${owner}/${name}`,
        undefined,
        signal,
      ),
      owner,
      name,
      expectedId,
    );
  } catch (error) {
    if (
      error instanceof DeploymentProviderError &&
      error.code === "http_error" &&
      error.status === 404 &&
      expectedId === undefined
    )
      return null;
    throw error;
  }
}

/** Creates a private organization repository once; conflicts and response loss require reconciliation. */
export async function createPrivateRepository(
  client: DeploymentProviderClient,
  owner: string,
  name: string,
  signal: AbortSignal,
): Promise<PrivateRepository> {
  validateNames(owner, name);
  try {
    const result = await client.request(
      "POST",
      `/api/v1/orgs/${owner}/repos`,
      {
        name,
        private: true,
        auto_init: false,
        description: "Generated by Wrenly",
      },
      signal,
    );
    return repository(result, owner, name);
  } catch (error) {
    throw error;
  }
}
