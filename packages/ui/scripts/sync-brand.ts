/** Regenerates inline bird artwork and browser icons from their separate designer-owned originals.
 * Trusted repository artwork is parsed at development time, never injected as HTML.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";

const root = resolve(import.meta.dir, "../../..");
function artwork(name: string): { viewBox: string; paths: { d: string; fill: string; opacity: number }[] } {
  const svg = readFileSync(resolve(root, `packages/ui/src/brand/${name}.svg`), "utf8");
  const viewBox = svg.match(/viewBox="([^"]+)"/)?.[1];
  const paths = [...svg.matchAll(/<path\b([^>]+)\/?\s*>/g)].map((match) => {
    const d = match[1]?.match(/\bd="([^"]+)"/)?.[1];
    const fill = match[1]?.match(/\bfill="([^"]+)"/)?.[1];
    if (!d || !fill) throw new Error("Brand paths require explicit geometry and fill.");
    const opacity = Number(match[1]?.match(/\bfill-opacity="([^"]+)"/)?.[1] ?? 1);
    if (!Number.isFinite(opacity) || opacity < 0 || opacity > 1) throw new Error("Invalid path opacity.");
    return { d, fill, opacity };
  });
  if (!viewBox || paths.length !== 7) throw new Error("Expected the seven-layer Wrenly bird.");
  return { viewBox, paths };
}
const light = artwork("w-icon");
const dark = artwork("w-icon-on-dark");
if (light.viewBox !== dark.viewBox) {
  throw new Error("Light and dark artwork must share a view box.");
}
writeFileSync(resolve(root, "packages/ui/src/brand/artwork.ts"),
  `// Generated by bun run brand:sync in packages/ui. Edit the adjacent SVG originals.\nexport const BRAND_VIEW_BOX = ${JSON.stringify(light.viewBox)};\nexport const BRAND_PATHS = ${JSON.stringify(light.paths.map((path, i) => ({ d: path.d, darkD: dark.paths[i]!.d, light: path.fill, dark: dark.paths[i]!.fill, lightOpacity: path.opacity, darkOpacity: dark.paths[i]!.opacity })), null, 2)} as const;\n`);
// Favicons have their own square canvas/background; reusing the animated mark crops that artwork.
const faviconDirectory = resolve(root, "packages/ui/src/brand/favicons");
const faviconSources = ["w-favicon-on-light", "wrenly-favicon"].map(name => {
  const svg = readFileSync(resolve(faviconDirectory, `${name}.svg`), "utf8").trim();
  if (svg.match(/viewBox="([^"]+)"/)?.[1] !== "0 0 394 394")
    throw new Error("Expected the supplied square favicon canvas.");
  return svg.replace(/^<svg\b[^>]*>/, "").replace(/<\/svg>$/, "");
});
const icon = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 394 394"><style>.art-1{display:none}@media(prefers-color-scheme:dark){.art-0{display:none}.art-1{display:inline}}</style>${faviconSources.map((body, index) => `<g class="art-${index}">${body}</g>`).join("")}</svg>\n`;
for (const app of ["web", "docs"]) {
  writeFileSync(resolve(root, `apps/${app}/app/icon.svg`), icon);
  writeFileSync(resolve(root, `apps/${app}/app/apple-icon.png`), readFileSync(resolve(faviconDirectory, "wrenly-favicon.png")));
  mkdirSync(resolve(root, `apps/${app}/public`), { recursive: true });
  for (const name of ["w-favicon-on-light", "wrenly-favicon"])
    for (const extension of ["svg", "png"])
      writeFileSync(resolve(root, `apps/${app}/public/${name}.${extension}`), readFileSync(resolve(faviconDirectory, `${name}.${extension}`)));
}
for (const name of ["w-icon", "w-icon-on-dark"]) {
  writeFileSync(resolve(root, `apps/web/public/${name}.svg`), readFileSync(resolve(root, `packages/ui/src/brand/${name}.svg`)));
}
const lightMode = "--wrenly-light:inline;--wrenly-dark:none;";
const darkMode = "--wrenly-light:none;--wrenly-dark:inline;";
writeFileSync(resolve(root, "packages/ui/src/brand/palette.css"), `/* Generated from the supplied SVG palettes. */
.wrenly-brand{${lightMode}}
.wrenly-brand [data-artwork="light"]{display:var(--wrenly-light)}
.wrenly-brand [data-artwork="dark"]{display:var(--wrenly-dark)}
@media(prefers-color-scheme:dark){:root:not([data-theme="light"]):not(.light) .wrenly-brand{${darkMode}}}
:root[data-theme="dark"] .wrenly-brand,.dark .wrenly-brand{${darkMode}}
.wrenly-brand[data-mark-variant="on-primary"]{${darkMode}}
:root[data-theme="dark"] .wrenly-brand[data-mark-variant="on-primary"]{${lightMode}}
@media(prefers-color-scheme:dark){:root:not([data-theme="light"]) .wrenly-brand[data-mark-variant="on-primary"]{${lightMode}}}
`);
